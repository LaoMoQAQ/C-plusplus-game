#pragma once


#include "Story.h"

#include <string>

using namespace std;



// ==========================================================
// StoryParser
// ==========================================================
//
// 剧本解析器。把 UTF-8 文本脚本解析成 StoryEvent 列表。
//
// 支持的标签：
//   [背景] xxx.png      或 [背景] + 下一行
//   [立绘] xxx.png      或 [立绘] + 下一行
//   [BGM] / [SE]        预留
//   [角色名]            开始一段对话，下一段是台词
//   [选择]              选择事件，后面跟选项列表
//   [标签] name         打书签
//   [跳转] #name        跳到书签
//   [下一章] script/... 播完自动加载下一章
//   [结局分支]          根据好感度自动选结局
//   <n>                 等待 n 秒
//
// 带参数的标签支持单行（[标签] xxx）和两行（[标签]\nxxx）两种写法。
//
// 立绘约定：
//   [立绘] 必须紧跟在对应 [角色名] 之前，
//   中间不能夹别的 [角色名]，否则立绘会滞后一句。
//
// 选择语法：
//   1. 显示文本 | 好感度变化 -> 跳转目标
//   三个部分都可省略（除显示文本）。

class StoryParser
{

public:

    // 解析指定文件，把事件追加到 story。
    // 不清空 story 已有的 events（调用方负责）。
    bool Load(
        string file,
        Story& story
    );



private:

    // 清理单行文本：去 BOM、去行尾 \r 和空格。
    string Clean(string text);

};